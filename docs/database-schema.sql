COMMENT ON TABLE UTILISATEURS IS 'Comptes utilisateurs de la plateforme de domiciliation bancaire.';
COMMENT ON TABLE PARAMETRES IS 'Paramétrage fonctionnel (délais de relance, options métier).';
COMMENT ON TABLE DOSSIERS IS 'Table commune des dossiers de domiciliation (DIM/DEX).';
COMMENT ON TABLE DOSSIERS_IMPORTATION IS 'Données spécifiques aux dossiers d''importation (DIM).';
COMMENT ON TABLE DOSSIERS_EXPORTATION IS 'Données spécifiques aux dossiers d''exportation (DEX).';
COMMENT ON TABLE PIECES_JOINTES IS 'Pièces justificatives déposées pour un dossier DIM/DEX.';
COMMENT ON TABLE CHECKLIST_ITEMS IS 'Checklist de contrôle documentaire et d''exécution du dossier.';
COMMENT ON TABLE HISTORIQUE_ACTIONS IS 'Journal d''audit des actions utilisateur sur les dossiers.';
COMMENT ON TABLE RELANCES IS 'Traçabilité des relances automatiques/manuelles envoyées aux clients.';
COMMENT ON TABLE REGLEMENT_DATES IS 'Historique des dates de règlement (DIM) et encaissement (DEX).';

COMMENT ON COLUMN DOSSIERS.TYPE_DOSSIER IS 'Type de dossier : DIM (importation) ou DEX (exportation).';
COMMENT ON COLUMN DOSSIERS.NUMERO_ORDRE IS 'Numéro d''ordre réglementaire unique du dossier.';
COMMENT ON COLUMN DOSSIERS.OPERATEUR_NOM IS 'Importateur (DIM) ou exportateur (DEX).';
COMMENT ON COLUMN DOSSIERS.STATUT IS 'Statut courant du dossier selon le workflow métier.';
